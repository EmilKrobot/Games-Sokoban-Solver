sub init_four($bigpat) {
    my %four_hash;
    foreach my $v (@four) {
        my $bpat = "$bigpat";
        substr($bpat, $_, 1) =~ tr/03/47/ foreach (@$v);
        my $bstr = join('', map(substr($bpat, $_, 1), @$v));
        if ($bstr =~ /$fourrex/a) {
            my $num = 0;
            foreach my $i (0 .. 3) {
                if (substr($bstr, $i, 1) =~ /[47]/a) {
                    $num += $nums[$v->[$i]];
                }
            }
            if ($num) {
                unless ($four_hash{$num}++) {
                    push @Four, $num;
                }
            }
        }
    } ## end foreach my $v (@four)
    return;
} ## end sub init_four

