=head1 NAME

Games::Sokoban::Solver::Finder - the deadlock patterns of a push, found by playing a minigame

=head1 SYNOPSIS

    use Games::Sokoban::Solver::Finder ();

    # is this push a deadlock by itself?
    my $alive = Games::Sokoban::Solver::Finder::pat_soluble($pattern);

    # the sets of other boxes that make it one -- all patterns of a level
    my ($bloks, $report) = Games::Sokoban::Solver::Finder::blok_table(
        \%patterns, 'nbox' => $nbox, 'deadline' => Time::HiRes::time() + 30);

    # ... or one pattern, one range of sizes: the unit a pool of workers takes
    my $row = Games::Sokoban::Solver::Finder::blok_task($pattern, $kmax, 1, '', $deadline);
    my ($same_pattern, $k_done, $blok_string, $candidates, $seconds) = @$row;

=head1 DESCRIPTION

A B<pattern> is the window of a level round one push of a box, 5 cells wide
and 6 tall, written row by row as 30 digits: the pushed box in the fifth row,
third column, the player below it, and round them the walls (C<9>), the cells
boxes must avoid (C<2>), the goals (C<3>) and the free floor (C<0>) of the
level. The L<Games::Sokoban::Solver::Parser> cuts
such a window out for every push of its push graph and asks two questions of
it here.

The first: can the pushed box, alone, ever leave the window or reach a goal in
it? If not, the push is a deadlock by itself and the Parser removes it. The
second: which sets of other boxes, standing in the window when the push is
made, make the position dead although without the pushed box every one of
them could still get away? Each such set is a B<blok>, and the engines test
every push they consider against the bloks of its pattern.

Both are answered by playing a minigame: the window is laid into a grid 7 wide
and 8 tall with a ring of free floor round it, so the player can walk round it and a box
pushed onto the ring is gone; the positions are searched breadth first, with
every set of cells a bit mask in one integer. The sets are tried by size, 1,
2, 3 and so on, which is what makes a search cut short still sound: a set is
recorded only after both tests finished, so a cut leaves fewer bloks, never a
wrong one.

The Sokoban project computed these bloks once for 1.92 million patterns and
stored them; this distribution computes them when a level is solved, under a
time budget, so a level solved here may carry fewer bloks than the same level
had in that project. The report says how many patterns and sizes were done.

=head1 FUNCTIONS

=over 4

=item pat_soluble PATTERN

True when the pushed box of PATTERN can, alone, leave the window or reach a
goal in it.

=item blok_task PATTERN, KMAX, KFROM, BLOKS_SO_FAR, [DEADLINE]

The bloks of one pattern for the sizes KFROM to KMAX, continuing from
BLOKS_SO_FAR (the pattern's blok string of the sizes before KFROM, or the
empty string). DEADLINE is an absolute time as L<Time::HiRes/time> gives it,
or C<undef> for none. Returns an array reference C<[pattern, k_done,
blok_string, candidates, seconds]>: the last size finished, the bloks as a
string (sets of pattern cells 0-29 comma-separated, sets separated by
semicolons, smallest first, no set containing a smaller one), the candidate
sets generated and the time taken.

=item blok_table PATTERNS, OPTIONS

The bloks of a whole level: PATTERNS is a hash reference whose keys are the
patterns; OPTIONS are C<nbox> (the boxes of the level; a set of that many
boxes can never occur, so sizes stop at C<nbox - 1>), C<deadline> (absolute,
optional) and C<kmax_of> (a hash reference of a pattern's own largest size,
optional). Every pattern is done to size 3 first, then the rest, cheapest
patterns first; past the deadline the pattern in hand ends with what it has
and no other is started. Returns the bloks as a hash reference (pattern to
blok string) and the report, an array reference of C<[pattern, kmax, k_done,
candidates, seconds]> rows in the order worked.

=back

