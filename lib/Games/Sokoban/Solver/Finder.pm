sub tobignum ($bl) {
    my ($num) = 0;
    foreach $_ (split(/,/a, $bl, 0)) {
        $num += $nums[$to_big{$_}];
    }
    return $num;
}

sub bloknum($bstr) {
    @Blok = ();
    return unless $bstr;
    my @blk = split(/;/a, $bstr, 0);
    @Blok = map(tobignum($_), @blk);
    return;
}

