# THE DEADLOCK PATTERNS OF A PUSH, FOUND BY PLAYING A MINIGAME.
#
# A pattern is the window of a level round one push, 5 cells wide and 6 tall,
# written row by row as 30 digits: the pushed box in the fifth row, third
# column (index 22), the player below it in the sixth row; 9 a wall, 2 a cell
# boxes must avoid, 3 a goal, 0 free floor. The Parser cuts such a window out of the
# level for every push of its push graph (standardized, so that windows that
# look alike are one pattern) and asks two questions of it here:
#
#   pat_soluble  can the pushed box, alone, ever get out of the window or onto
#                a goal in it?  If not the push is a deadlock by itself and the
#                Parser removes it from the push graph.
#   blok_task    which SETS of other boxes in the window, standing there when
#                the push is made, make the position dead -- although without
#                the pushed box they could all still get away?  Every such set
#                is a 'blok'; the engines test every push against the bloks of
#                its pattern.
#
# THE MINIGAME. The window is laid into a grid 7 wide and 8 tall (56 cells; the
# box at 38, the player at 45) with a ring of free floor round it, so the player
# can walk round the window and a box pushed onto the ring is simply gone (the
# ring is %border). Every set -- walls, boxes, goals, the cells the
# player can reach -- is a 56-bit mask in one integer, so membership is one
# bitwise AND; paint() is the player's flood fill, memoized on the position;
# %to_out holds the ray of cells behind a push out to the ring (a clear ray
# means the box can be shoved out), free_box() iterates that to a fixed point
# and keeps the boxes that cannot be discarded, is_soluble() is the breadth
# first search over what is left. A box is also gone when it reaches a goal.
#
# THE TWO TESTS THAT DEFINE A BLOK, per candidate set @c of k boxes: the window
# WITHOUT the pushed box must still be soluble (is_soluble(0, @c) true --
# otherwise the deadlock was there before the push and is not this push's to
# flag), and WITH it must be dead (is_soluble(1, 38, @c) false). The sets are
# enumerated by size k = 1, 2, 3 ... ascending, and that order carries the
# proof: with the pushed box present, the moment free_box() can discard ANY box
# the set reduces to a smaller one already decided (either a blok, and the
# superset is pruned anyway, or soluble), so is_soluble with $flag set returns
# at once. The shortcut is exact only because every smaller size was finished
# first. @Four are the fast rejects -- box groups in 2 x 2 squares, 3 x 3
# windows and 2 x 4 rectangles that the window's own walls make dead -- found
# by regular expressions over the window (generated by Regexp::Assemble from
# the dead shapes: do not hand-edit them). clean() finishes a pattern: it drops
# every set that contains a smaller recorded blok.
#
# THE DEADLINE. A level's patterns are computed when the level is solved, under
# a budget, so find_blok() takes an absolute deadline and gives up a size k
# unfinished when it is past. A cut is sound: a set is recorded only after both
# tests ran to their end, and within one size every candidate is the same size,
# so no candidate of the cut round can be a proper subset of a blok of that
# round. Fewer bloks, never a wrong one -- the engines test (vb &. pv) eq pv
# vector by vector, and a missing superset costs nothing.
#
# Each pattern is independent of every other, so blok_task() -- one pattern,
# one range of sizes -- is the unit a pool of workers takes; blok_table() runs
# the tasks of a whole level one after another in the same order the pool would
# (every pattern to k <= 3 first, cheap everywhere and the most valuable sets,
# then the rest), and a pool-fed caller gets the same table.
#
# Lineage: Games::Sokoban::Finder of the Sokoban project, the generator that
# filled its pattern database (1.92 million patterns, 365 processor-days);
# the five static tables Common.pm served from pat_grid.stor are the literals
# below.
