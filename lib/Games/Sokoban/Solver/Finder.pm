sub init ($pattern) {
    my ($k, $kn, %wall, $p, @pata);
    clear_vars;
    my ($bigpat) = '00000000000000000000000000000000000000000000000000000000';
    @pata = split(//a, $pattern, 0);
    for (my $i = 0; $i < 30; ++$i) {
        $p = $pata[$i];
        substr($bigpat, $to_big{$i}, 1) = $p;
    }
    @pata = split(//a, $bigpat, 0);
    for (my $i = 0; $i < 56; ++$i) {
        $p  = $pata[$i];
        $kn = $nums[$i];
        if ($p eq '0') {
            push @Data, $i unless $border{$i};
        }
        elsif ($p eq '2') {
            $ObstNum += $kn;
        }
        elsif ($p eq '3') {
            push @Data, $i;
            push @Goal, $i;
            $GoalNum += $kn;
        }
        elsif ($p eq '7' or $p eq '8') {
            $GoalNum += $kn;
            push @Goal, $i;
        }
        elsif ($p eq '9') {
            $ObstNum += $kn;
            $Cgp     += $kn;
            $wall{$i} = 1;
        }
        else {
            Carp::confess("\nBAD PATTERN $bigpat\n") unless $p =~ /[456]/aa;
        }
    } ## end for (my $i = 0; $i < 56...)
    $Cgp += $nums[45];
    $bigpat =~ tr/45678/0023/;
    while (my ($k, $v) = each %cango) {
        $To_out{$k}{$_} = -1 foreach (@$v);
        next if $wall{$k};
        my (@zb) = grep((!$wall{$_}), @$v);
        if (@zb) {
            $Cango{$k} = [@zb];
        }
    }
    foreach my $x (keys %to_out) {
        my $num = $nums[$x];
        next if ($ObstNum & $num) == $num;
    XT: foreach my $t (keys %{ $to_out{$x}; }) {
            $num = $nums[$t];
            next if ($ObstNum & $num) == $num;
            my $v = $to_out{$x}{$t};
            foreach $_ (@$v) {
                $num = $nums[$_];
                next XT if ($ObstNum & $num) == $num;
            }
            my $xv = 0;
            $xv += $nums[$_] foreach (@$v);
            $To_out{$x}{$t} = $xv;
        }
    } ## end foreach my $x (keys %to_out)
    init_four($bigpat);
    init_nine($bigpat);
    init_eight($bigpat);
    return;
} ## end sub init

sub paint ($man, @bags) {
    my ($bt, $x, $pozice, $num, $cg, $obst);
    $pozice = pack('C*', $man, @bags);
    return $Memoize{$pozice} if exists $Memoize{$pozice};
    $bt   = 1;
    $obst = 0;
    $obst += $nums[$_] foreach (@bags);
    $cg = $obst + $nums[$man];
    $Buf[0] = $man;

    for (my $bh = 0; $bh < $bt; ++$bh) {
        $x = $Buf[$bh];
        foreach my $t (@{ $Cango{$x}; }) {
            $num = $nums[$t];
            if (($cg & $num) != $num) {
                $cg += $num;
                $Buf[$bt++] = $t;
            }
        }
    }
    $cg = $cg ^ $obst;
    $Memoize{$pozice} = $cg;
    return $cg;
} ## end sub paint

sub box_out ($baggage_bits) {
    my ($pozice, $bt, $cg, $x, $obst, $num, $numx);
    $bt     = 1;
    $Buf[0] = 45;
    $num    = $baggage_bits + $nums[38];
    $cg     = $Cgp + $num;
    $obst   = $ObstNum + $num;
    for (my $bh = 0; $bh < $bt; ++$bh) {
        $x = $Buf[$bh];
        foreach my $t (@{ $Cango{$x}; }) {
            $numx = $nums[$t];
            if (($num & $numx) == $numx) {
                return 1 if $border{ 2 * $t - $x } or ($To_out{$x}{$t} & $obst) == 0;
            }
            next if ($cg & $numx) == $numx;
            $cg += $numx;
            $Buf[$bt++] = $t;
        }
    }
    return 0;
} ## end sub box_out

sub free_box ($man, @baggage) {
    my ($found, @zb, $flag, $cg, $obst, $num);
    $found = 1;
    while ($found) {
        $found = 0;
        @zb    = ();
        $cg    = paint($man, @baggage);
        $obst  = $ObstNum;
        $obst += $nums[$_] foreach (@baggage);
    BOX: foreach my $bx (@baggage) {
            $flag = 0;
        CGO: foreach my $t (@{ $Cango{$bx}; }) {
                $num = $nums[$t];
                if (($num & $cg) == $num) {
                    if (($obst & $To_out{$t}{$bx}) == 0) {
                        $flag  = 1;
                        $found = 1;
                        last CGO;
                    }
                }
            }
            push @zb, $bx unless $flag;
        }
        return () unless @zb;
        $num = 0;
        $num += $nums[$_] foreach (@zb);
        return () if ($GoalNum & $num) == $num;
        @baggage = @zb;
    } ## end while ($found)
    return @baggage;
} ## end sub free_box

sub pat_soluble ($pattern) {
    my ($pozice, %seen, $cg, $obst_vec, @pokr, $s, $child, $num);
    return 1 if substr($pattern, 22, 1) eq '7';
    init($pattern);
    $pozice        = pack('CC', 45, 38);
    $seen{$pozice} = 1;
    @pokr          = $pozice;
    while (@pokr) {
        $pozice = shift @pokr;
        my ($man, $box) = unpack('CC', $pozice);
        $cg       = paint($man, $box);
        $obst_vec = $ObstNum + $nums[$box];
        foreach my $t (@{ $Cango{$box}; }) {
            $num = $nums[$t];
            next if ($obst_vec & $num) == $num;
            $s   = 2 * $box - $t;
            $num = $nums[$s];
            next     if ($cg & $num) == 0;
            return 1 if $border{$t} or ($To_out{$box}{$t} & $obst_vec) == 0;
            $s = $nums[$t];
            return 1 if ($GoalNum & $s) == $s;
            $child = pack('CC', $box, $t);
            next if $seen{$child}++;
            push @pokr, $child;
        }
    } ## end while (@pokr)
    return 0;
} ## end sub pat_soluble

sub is_soluble ($flag, @baggage) {
    my (
        %seen, $pozice, $child, @heap,    $n_open,   @nb,    @zb,      $s, $num,
        $obst, $cg,     $moves, $pattern, $childpat, $start, $bag_num, $child_num
       );
    $start   = $#baggage;
    @baggage = free_box(45, @baggage);
    return 1 unless @baggage;
    return 1 if $flag and $#baggage < $start;
    $num = 0;
    $num += $nums[$_] foreach (@baggage);
    return 1 if ($num & $GoalNum) == $num;
    $pozice = pack('C*', 45, (sort {$a <=> $b} @baggage));
    return 0 if $Bad{$pozice};
    $n_open        = 1;
    $seen{$pozice} = 1;
    @heap          = $pozice;
SOLM: while ($n_open) {
        $pozice = shift @heap;
        --$n_open;
        my ($man, @bags) = unpack('C*', $pozice);
        next if (exists $Bad{$pozice});
        $cg      = paint($man, @bags);
        $bag_num = 0;
        $bag_num += $nums[$_] foreach (@bags);
        foreach $_ (@Four) {
            if (($bag_num & $_) == $_) {
                $Bad{$pozice} = 1;
                next SOLM;
            }
        }
        $obst  = $ObstNum + $bag_num;
        $moves = 0;
        foreach my $bx (@bags) {
        MV: foreach my $t (@{ $Cango{$bx}; }) {
                $num = $nums[$t];
                next if ($obst & $num) == $num;
                $s = 2 * $bx - $t;
                $s = $nums[$s];
                next if ($cg & $s) == 0;
                ++$moves;
                if ($border{$t} or ($To_out{$bx}{$t} & $obst) == 0) {
                    @nb = grep(($_ != $bx), @bags);
                    return 1 unless @nb;
                }
                else {
                    @nb = (sort {$a <=> $b} map(($_ == $bx ? $t : $_), @bags));
                }
                $child_num = 0;
                $child_num += $nums[$_] foreach (@nb);
                return 1 if ($GoalNum & $child_num) == $child_num;
                $child = pack('C*', $bx, @nb);
                next MV if $Bad{$child};
                @zb = free_box($bx, @nb);
                if ($#zb != $#nb) {
                    return 1 unless @zb;
                    $child_num = 0;
                    $child_num += $nums[$_] foreach (@zb);
                    return 1 if ($GoalNum & $child_num) == $child_num;
                    $child = pack('C*', $bx, @zb);
                }
                next MV if $seen{$child}++;
                foreach $_ (@Four) {
                    if (($child_num & $_) == $_) {
                        $Bad{$child} = 1;
                        next MV;
                    }
                }
                push @heap, $child;
                ++$n_open;
            } ## end MV: foreach my $t (@{ $Cango{$bx...}})
        } ## end foreach my $bx (@bags)
        $Bad{$pozice} = 1 unless $moves;
    } ## end SOLM: while ($n_open)
    return 0;
} ## end sub is_soluble

# The k-element subsets of @$set, one per call, in the order of their indices
# (0,1,2 / 0,1,3 / ... ), undef when they are exhausted. The result of a round
# does not depend on this order -- clean() sorts, and the candidates of one
# round are all of one size -- so any complete enumeration gives the same table.
sub _combinations ($set, $k) {
    my $n = scalar @$set;
    return sub {undef}
        if $k < 0 or $k > $n;
    my @idx  = (0 .. $k - 1);
    my $done = 0;
    return sub {
        return undef if $done;
        my @pick = @{$set}[@idx];
        my $i    = $k - 1;
        while ($i >= 0 and $idx[$i] == $n - $k + $i) {--$i}
        if ($i < 0) {$done = 1}
        else {
            ++$idx[$i];
            $idx[$_] = $idx[$_ - 1] + 1 for $i + 1 .. $k - 1;
        }
        return \@pick;
    };
} ## end sub _combinations

# One round: every set of $k boxes over the free cells of the pattern, tested
# unless a fast reject or a recorded blok covers it. Returns 1 when the round
# ran to its end, 0 when $deadline cut it (the bloks found so far stay): the
# clock is read before the round and then every 256 candidates.
sub find_blok ($k, $deadline = undef) {
    return 0 if defined $deadline and Time::HiRes::time() > $deadline;
    my $iter = _combinations(\@Data, $k);
    my $n    = 0;
ITER: while (my $c = $iter->()) {
        ++$Count{'generated'};
        return 0 if defined $deadline and ++$n % 256 == 0 and Time::HiRes::time() > $deadline;
        my $c_n = 0;
        $c_n += $nums[$_] foreach (@$c);
        my $c_p = $c_n + 274877906944;    # $nums[38], the pushed box
        next if (($c_p & $GoalNum) == $c_p);
        foreach $_ (@Four, @Blok) {
            next ITER if (($c_n & $_) == $_);
        }
        next if box_out $c_n;
        ++$Count{'solver'};
        if (is_soluble 0, @$c) {
            unless (is_soluble 1, 38, @$c) {
                ++$Count{'found'};
                push @Blok, $c_n;
            }
        }
    } ## end ITER: while (my $c = $iter->)
    return 1;
} ## end sub find_blok

sub bloksort {
    my $ca = $a =~ tr/,//;
    my $cb = $b =~ tr/,//;
    my $r  = $ca <=> $cb;
    return $r if $r;
    my $sa = join('', map(sprintf('%04d', $_), split(/,/a, $a, 0)));
    my $sb = join('', map(sprintf('%04d', $_), split(/,/a, $b, 0)));
    return $sa cmp $sb;
}

# The bloks recorded so far as one string: sets of pattern cells (0-29),
# comma-separated, the sets separated by semicolons, smallest sets first,
# every set that contains a smaller recorded set left out.
sub clean () {
    my (@vse)   = ();
    my (@plati) = ();
    @Blok = uniq @Blok;
    foreach my $blok_num (@Blok) {
        my @str        = split(//a, unpack('b*', pack('Q', $blok_num)));
        my $small_blok = join(',', map($to_small{$_}, grep {$str[$_] == 1} 0 .. $#str));
        push @vse, $small_blok;
    }
    @vse = sort bloksort @vse;
    my %seznam;
    foreach my $bl (@vse) {
        my $num = 0;
        $num += $nums[$_] foreach (split(/,/a, $bl, 0));
        $seznam{$num} = $bl;
        push @plati, $num;
    }
    for (my $i = 0; $i < $#plati; ++$i) {
        my $n = $plati[$i];
        for (my $j = $i + 1; $j <= $#plati; ++$j) {
            my $m = $plati[$j];
            if (($m & $n) == $n) {
                delete $seznam{$m};
            }
        }
    }
    return join(';', (sort bloksort values %seznam));
} ## end sub clean

# ONE PATTERN, THE SIZES $k_from .. $kmax, under a deadline: the unit of work a
# pool hands to a worker. $bloks_so_far is the pattern's blok string from the
# sizes before $k_from (the result so far and the prune for what follows).
# Returns [pattern, k_done, blok_string, candidates, seconds]: k_done is the
# last size that ran to its end (k_from - 1 when the first was cut), the blok
# string holds every blok found, the cut round's included.
sub blok_task ($pattern, $kmax, $k_from, $bloks_so_far, $deadline = undef) {
    my $t0 = Time::HiRes::time();
    init($pattern);
    bloknum($bloks_so_far // '');
    %Count = ('generated' => 0, 'solver' => 0, 'found' => 0);
    my $k_done = $k_from - 1;
    for my $k ($k_from .. $kmax) {
        last unless find_blok($k, $deadline);
        $k_done = $k;
    }
    return [$pattern, $k_done, clean(), $Count{'generated'}, Time::HiRes::time() - $t0];
}

# THE BLOKS OF A WHOLE LEVEL, one task after another, in the order a pool takes
# them: first every pattern to size 3 (cheap everywhere, the smallest sets
# prune the most), then the rest size by size, cheapest patterns first.
#
#   my ($bloks, $report) = blok_table(\%patlist, nbox => $nbox, deadline => $t);
#
# %patlist: pattern => anything (the keys are what matters). nbox: the boxes of
# the level; a set of nbox or more boxes can never occur, so the largest size
# tried is min(nbox - 1, the free cells of the pattern) -- or kmax_of->{pattern}
# when given. deadline: an absolute time (Time::HiRes), undef for none; past
# it the pattern in hand ends with what it has and no other is started.
# Returns the bloks (pattern => blok string) and the report, one row per
# pattern in the order worked: [pattern, kmax, k_done, candidates, seconds].
sub blok_table ($patlist, %opt) {
    my $nbox     = $opt{'nbox'} // Carp::croak('blok_table: nbox is needed');
    my $deadline = $opt{'deadline'};
    my $kmax_of  = $opt{'kmax_of'} // {};
    my %kmax     = map {
        my $free = tr/03//;
        $_ => ($kmax_of->{$_} // ($nbox - 1 < $free ? $nbox - 1 : $free))
    } keys %$patlist;
    my @order = sort {$kmax{$a} <=> $kmax{$b} or $a cmp $b} keys %$patlist;
    my (%bloks, %row);
    $row{$_} = [$_, $kmax{$_}, 0, 0, 0] for @order;
    my $cut = 0;
    for my $pass ([1, 3], [4, undef]) {
        my ($from, $to) = @$pass;
        for my $p (@order) {
            last if $cut;
            my $kmax = $to // $kmax{$p};
            $kmax = $kmax{$p} if $kmax > $kmax{$p};
            next if $kmax < $from;
            my $r = blok_task($p, $kmax, $from, $bloks{$p} // '', $deadline);
            $bloks{$p} = $r->[2];
            $row{$p}[2] = $r->[1];
            $row{$p}[3] += $r->[3];
            $row{$p}[4] += $r->[4];
            $cut = 1 if $r->[1] < $kmax;
        }
    } ## end for my $pass ([1, 3], [...])
    $bloks{$_} //= '' for @order;
    return (\%bloks, [map {$row{$_}} @order]);
} ## end sub blok_table
1;
